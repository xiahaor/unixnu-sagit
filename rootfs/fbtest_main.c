static long fb_errors;

static const unsigned char *glyph_for(char c)
{
	unsigned i;
	for (i = 0; i < sizeof(glyphs) / sizeof(glyphs[0]); i++) {
		if (glyphs[i].c == c) {
			return glyphs[i].rows;
		}
	}
	return glyphs[0].rows;
}

/* Draw one string; every set font pixel becomes a scale x scale rectangle. */
static void draw_text(unsigned x, unsigned y, unsigned scale, unsigned color, const char *s)
{
	unsigned cx = x;
	while (*s) {
		const unsigned char *rows = glyph_for(*s);
		unsigned r, c;
		for (r = 0; r < 8; r++) {
			unsigned char bits = rows[r];
			c = 0;
			while (c < 8) {
				if (bits & (0x80 >> c)) {
					unsigned run = 1;
					while (c + run < 8 && (bits & (0x80 >> (c + run)))) {
						run++;
					}
					if (fb_fill(cx + c * scale, y + r * scale,
					    run * scale, scale, color) != 0) {
						fb_errors++;
					}
					c += run;
				} else {
					c++;
				}
			}
		}
		cx += 9 * scale;	/* 8 pixels plus one column of spacing */
		s++;
	}
}

void main_user(void)
{
	long r1, r2, r3;

	/* No console output at all: the video console re-renders its text rows
	 * whenever it prints, which would paint over whatever we draw here. */
	con = svc3(5, (long)"/dev/console", 6, 0);
	if (con < 0) {
		con = 1;
	}

	r1 = fb_fill(80, 1050, 920, 180, 0x00FF0000);
	r2 = fb_fill(80, 1280, 920, 180, 0x0000FF00);
	r3 = fb_fill(80, 1510, 920, 180, 0x000000FF);

	fb_errors = 0;
	if (fb_fill(60, 1030, 960, 6, 0x00FFFFFF) != 0) {
		fb_errors++;
	}
	if (fb_fill(60, 1704, 960, 6, 0x00FFFFFF) != 0) {
		fb_errors++;
	}
	if (fb_fill(60, 1030, 6, 680, 0x00FFFFFF) != 0) {
		fb_errors++;
	}
	if (fb_fill(1014, 1030, 6, 680, 0x00FFFFFF) != 0) {
		fb_errors++;
	}

	draw_text(90, 1700, 5, 0x00FFFFFF, "SAGIT");
	draw_text(90, 1800, 4, 0x00FFFF00, "XNU XIAOMI 6");

	svc3(1, (r1 == 0 && r2 == 0 && r3 == 0 && fb_errors == 0) ? 0 : 1, 0, 0);
	for (;;) {
	}
}
